// Keeps the <link rel="modulepreload"> list in index.html in step with the real import graph.
// The game ships as plain ES modules (no bundler), so without these hints the browser finds each
// file only after its importer has downloaded and parsed: a chain several modules deep. Listing
// the whole graph up front lets it fetch every module in parallel.
//   node tools/preload.mjs          rewrite the block in index.html
//   node tools/preload.mjs --check  exit 1 if it is out of date (also run by tests/preload.test.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- modulepreload:start (generated by tools/preload.mjs) -->';
const END = '<!-- modulepreload:end -->';
const IMPORTS = /(?:^|\n)\s*(?:import|export)\s[^'";]*?from\s*['"]([^'"]+)['"]|(?:^|\n)\s*import\s*['"]([^'"]+)['"]/g;

// the import map in index.html, as [prefix, target-dir-or-file] pairs
function importMap(html) {
  const m = html.match(/<script type="importmap">([\s\S]*?)<\/script>/);
  return Object.entries(JSON.parse(m[1]).imports);
}

function resolve(spec, from, map) {
  if (spec.startsWith('.')) return path.resolve(path.dirname(from), spec);
  for (const [k, v] of map) {
    if (k.endsWith('/') ? spec.startsWith(k) : spec === k) return path.resolve(root, v + spec.slice(k.length));
  }
  return null; // a bare specifier the map does not know: nothing to preload
}

// every module reachable from src/main.js, in the order a browser would meet them
export function moduleGraph(html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')) {
  const map = importMap(html);
  const seen = new Set(), order = [];
  const queue = [path.join(root, 'src/main.js')];
  while (queue.length) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    order.push(path.relative(root, file).split(path.sep).join('/'));
    const src = fs.readFileSync(file, 'utf8');
    for (const m of src.matchAll(IMPORTS)) {
      const target = resolve(m[1] || m[2], file, map);
      if (target) queue.push(target);
    }
  }
  return order;
}

export function render(html) {
  const links = moduleGraph(html).map((f) => `<link rel="modulepreload" href="${f}">`).join('\n');
  return `${START}\n${links}\n${END}`;
}

export function update(html) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0) throw new Error('index.html is missing the modulepreload markers');
  return html.slice(0, a) + render(html) + html.slice(b + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  const next = update(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('index.html modulepreload list is out of date: run node tools/preload.mjs'); process.exit(1); }
    console.log('modulepreload list is current');
  } else {
    fs.writeFileSync(file, next);
    console.log(`wrote ${moduleGraph(html).length} modulepreload links`);
  }
}
